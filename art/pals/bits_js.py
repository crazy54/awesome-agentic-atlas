"""Write docs/assets/archie-bits.js from the bits' staging files, art/pals/bits/<bit_name>.js.

    python art/pals/bits_js.py            (build_bits.py runs it too)

Each bit's staging is its own file beside its clips (`glass_door.py` and `glass_door.js`), so the bits can be
written side by side without touching one shared file; this joins them into the one module the page loads,
in name order. A staging file is one JavaScript object expression in parentheses, its comments included:

    // The glass door: ...
    ({
      cast: ["archie"],
      pages: ["repo"],
      ...
    })

and its bit's name is the file's, with dashes: `glass_door.js` is "glass-door". The stage fetches each pal's
clip file for a bit, `pals/bits/<bit>@<pal>.glb`, from the bit's cast unless the bit names its own `packs`.
"""
from __future__ import annotations

import re
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "docs" / "assets" / "archie-bits.js"
PACKS = HERE.parent.parent / "docs" / "assets" / "pals" / "bits"

HEADER = """// GENERATED by art/pals/bits_js.py from art/pals/bits/*.js -- edit those, not this.
//
// The pals' bits: the gags Archie, Zip and Brick play over the page, on the stage in archie-stage.js. Each
// bit says who is in it (`cast`), where it can happen (`pages`: the page families of archie-stage.js's
// `where()`), whether it can happen now (`ready(s)`: its element on screen, and room around it), and how it
// goes (`play(s)`). Its clips are art/pals/bits/<bit>.py, baked by art/pals/build_bits.py into
// assets/pals/bits/<bit>@<pal>.glb; how to write one is art/pals/BITS.md.
//
// The rules every bit keeps: nothing it draws takes a pointer event or is announced; nothing of the page's
// is moved, covered for long or restyled except through `s.page`, which restores it; nothing flashes faster
// than three times a second; and the reader's own cursor, text and numbers are never touched -- a cursor, a
// card or a star in a bit is a picture of one.
"""


def main():
    entries = []
    for f in sorted(HERE.glob("bits/*.js")):
        name = f.stem.replace("_", "-")
        src = f.read_text(encoding="utf-8").replace("\r\n", "\n").strip()
        if not re.search(r"\(\s*\{", src) or not src.rstrip().endswith(")"):
            raise SystemExit(f"{f.name}: a staging file is one object expression in parentheses")
        # a pal in the cast with no clips of his own in this bit has no file: say so, so that the stage doesn't
        # ask for one (a 404, and a warning in the reader's console)
        cast = re.search(r"cast:\s*\[([^\]]*)\]", src)
        pals = re.findall(r"[\"']([a-z]+)[\"']", cast.group(1)) if cast else []
        missing = [p for p in pals if not (PACKS / f"{name}@{p}.glb").is_file()]
        if missing and "packs:" not in src:
            packs = ", ".join(f'{p}: ' + ("null" if p in missing else f'"pals/bits/{name}@{p}.glb"') for p in pals)
            head, sep, rest = src.partition("\n(")          # after the bit's comment, round its object
            wrap = f"Object.assign({{packs: {{{packs}}}}}, "
            src = f"{head}\n{wrap}({rest})" if sep else f"{wrap}{src})"
        body = "\n".join("  " + line if line else "" for line in src.split("\n"))
        entries.append(f'  "{name}":\n{body},')
    text = HEADER + "export const BITS = {\n" + "\n\n".join(entries) + "\n};\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(entries)} bits)")


if __name__ == "__main__":
    main()
