"""Render one Open Graph card per view, so a shared link previews as the view it actually is.

`19_pages.py` and `20_landing.py` both used to point `og:image` at
`opengraph.githubassets.com/1/<repo>`, which is the same generic repository card on all 157 URLs this
site publishes. The whole pitch is that "the best Claude Code observability tool" is a *link*; in
Slack, Discord, X and iMessage that link looked identical to a link to the repository's front page --
which is the one surface where the crossing this site exists to show does not exist at all.

That card is now the fallback on both stages rather than the default, and it is a build-time fallback:
each page ships exactly one `og:image`, chosen by whether the file this stage writes is on disk.

  docs/og/root.png             1, the unfiltered view -- the bare site link
  docs/og/topic-<slug>.png     14, one per topic
  docs/og/target-<slug>.png    12, one per target
  docs/og/cards.json           what each card says, and the signature that decides re-rendering

  python scripts/23_og.py                   in GitHub Actions, which is the only place this publishes
  python scripts/23_og.py --out build/og    render somewhere other than what Pages serves
  python scripts/23_og.py --local           publish from this machine anyway, knowingly

After `20_landing.py`, and it reads the dataset through that stage's own `plan()` rather than
regrouping 1,294 rows a second time: a card and the page it belongs to cannot then disagree about a
count or about which three projects are the biggest. Nothing else is imported from it, so the two
stages stay independently runnable.

Seven decisions, in the order they cost the most.

The root page is a view like any other -- the one with no filter -- and it gets its card from the same
two functions. It is the only URL here anybody actually pastes into Slack, and until `root.png` existed
it was the only URL still previewing as the generic repository card that this whole stage exists to
replace: the deep links nobody shares had a real card and the front door did not. What it carries is
the one thing `opengraph.githubassets.com` cannot, because that image is rendered from a repository name
and a description: the size of the dataset. Project count, source lists, topics and the snapshot date,
which are the same four numbers `docs/index.html` prints in its own header, out of the same
`data.json`. `cards()` emits it ahead of the 26 and `card_html` draws it unchanged; the only
generalisation either needed was to stop hardcoding the host line's suffix, so that the root card can
carry a date there and a facet card can carry nothing, which is what it carried before.

27 cards, not 157. The 130 crossings reuse their topic's card. What a per-crossing image would add
over its topic's is that cell's own count and top three -- and `20_landing.py` already writes both
into the crossing's `<title>` and `<meta name=description>`, which is the text every one of those
scrapers renders beside the image. The bill for the duplicate is six times the bytes in a format that
cannot delta-compress: every generated byte is committed, because Pages serves this branch's `docs/`
folder. So the card says "every harness" or "every topic" out loud, and a topic card sitting beside a
crossing page's own "12 projects that plug into Claude Code" cannot be read as a claim about that
cell. To reverse the decision, drop the `bool(p.cat) == bool(p.tgt)` skip in `cards()` and give the
crossings a `topic-<a>--target-<b>.png`; nothing else in this stage counts on there being 27.

Nothing that moves daily goes on a facet card. These pages lead with combined stars and a snapshot date
and neither is on one of the 26, because a PNG whose pixels moved is a whole new object in the pack for
ever -- there is no such thing as a small edit to one. The count is floored to a multiple of ten and
suffixed `+` for the same reason: "470+ projects" stays true about ten times longer than "479 projects"
does, and a social card is not where anybody reads a precise number. The three names are the top three
by stars, printed in alphabetical order under a label rather than numbered, because the *set* of the
three biggest projects in a facet holds for months while the order of the second and third flips
whenever they trade a few hundred stars -- and a numbered list would turn every one of those flips into
a rewrite of the whole file.

`root.png` is the one exception, and it is a knowing one: it carries `data.json`'s snapshot date, so it
is re-rendered whenever the dataset is refetched. That is up to 52 rewrites of one ~25 KB file a year
against zero, which is the price of the card answering "is this current?" for the one URL anybody
shares -- an atlas whose whole claim is that it is rebuilt daily cannot make that claim on a card that
is deliberately undated. Two things follow, and both are real. `weekly.yml` runs this stage and
`daily.yml` does not, so between weekly runs the date on the card is behind the date the page prints:
the card is never wrong about a snapshot that existed, but it can be up to six days older than the
page's. And the floored count moves the same way -- "1,290+" is true the day it is rendered and stays
true while the index grows, but a week of *net removals* below 1,290 would leave it overstating until
the next weekly run. Drop `"note"` from the root record in `cards()` to take the date back off and get
the facet cards' churn profile; nothing else depends on it.

A card is re-rendered only when what it says or how it looks changes, and "how it looks" now includes
the thing that draws it. `docs/og/cards.json` holds the exact strings that went onto each card plus a
signature over them, over `PALETTE`, over `FONT`, over the renderer's major version and over
`TEMPLATE`. `PALETTE` is in there rather than trusted to a human because the colours are the half of
"how it looks" that a re-theme actually touches, and a cache key that does not cover its own input
ships a stale artefact and reports success -- see `signature()`. `FONT` and the Chromium major are in
there for the same reason and were added later, on JFH-283, because they were the remaining half:
`weekly.yml` does `pip install --upgrade playwright` and then `playwright install chromium`, so the
rasterizer moves every few weeks, and the stack this stage used to name resolved to Segoe UI on Windows
and DejaVu Sans on the runner. `TEMPLATE` stays for what the hash still cannot see: bump it to force the
set through after a layout change, and only after one. The optional `"note"` key is there for exactly
that reason -- a facet record does not carry it, so a facet signature did not move when the root card
was added, so this stage rendered one file rather than 27.

Which raises the objection this file used to answer by leaving the renderer out of the key: a Chromium
update would then rewrite all 27 cards, and text rendered a pixel differently is 27 new objects at
~540 KB a set, thirteen majors a year. That is answered instead by `main()` reading the committed PNG
and writing only when the new bytes differ. A renderer bump therefore costs 27 browser launches and,
when the pixels come out the same, nothing at all in the history -- so the byte-thrift the old design
bought by not noticing the rasterizer is now bought by noticing it and then checking. What the old
design could not do at any price is the case that made this a bug: one facet's text changes, that single
card re-renders on the current Chromium, and the set is left as 26 cards from one rasterizer and one
from another, with every signature matching and the ledger reporting success.

Committed rather than left in `cache/`, which is gitignored and restored best-effort -- a cache miss
there would be indistinguishable from 27 changed cards and would cost the history ~540 KB to find that
out.

CI is the only thing that renders into `docs/og/`. Every committed card was drawn on Windows, where the
font stack this stage used to carry resolved to Segoe UI; `ubuntu-latest` has no Segoe UI and no
font-installation step, so it drew DejaVu Sans instead -- different metrics, different line breaks, and
JFH-224 measured the result at 0 of 27 identical, 7.67%-12.96% of pixels moved. Naming one family kills
the fallback chain that made the choice machine-dependent, and `main()` refusing to write into
`docs/og/` outside Actions kills the machine that was making the other choice. `--out` and `--local` are
both still there for looking at a design change locally; neither publishes.

A missing browser is not an error. Same contract as `15_shots_all.py` and `06_web_shots.py`: one
subprocess per image, `chrome.find()` may return None, and None degrades. It degrades better here
than there, because these cards are committed -- so "no Chromium" means the cards already on disk are
left exactly as they are, which is also what a card whose content did not change gets. The only state
this cannot serve is a view that has never been rendered, and the page stages handle that one by
listing `docs/og/` and falling back to the repository card for any page whose file is not there --
`20_landing.py` for the 156 facet pages, `19_pages.py` for the root. Note which way round the ordering
runs: both of those stages emit their `og:image` *before* this one writes the images, so a card's first
ever render lands one build after the tag that would point at it. Committing the card is what closes
that gap; a card generated and not committed leaves the page on the repository fallback for ever.

Chrome's PNG is re-encoded as an indexed one, with `zlib` and nothing else. A card is flat fills and
antialiased text, so 8-bit RGB spends three bytes on a palette of about 1,900 colours of which 256
cover 99.2% of the pixels: indexing costs ~24 KB where Chrome writes ~60 KB, and the 2.5x applies to
every rewrite for the life of the repository. Lossless when a render has 256 colours or fewer, and
nearest-neighbour among the 256 most frequent otherwise, which on this design is invisible -- every
colour in the image is a point on a blend between one of six inks and one of three backgrounds, so
the nearest palette entry is a neighbour on the same ramp. Anything this cannot parse as an 8-bit
non-interlaced RGB or RGBA PNG is written through unchanged: a smaller card is worth having and a
corrupt one is not.

Dark only. The site ships a light theme and this does not, because a scraper never tells us which one
the reader has and dark is the designed mode -- the mode whose eight neutrals and two accents were
measured. A light card would be a second 27 files that nobody can request.
"""
