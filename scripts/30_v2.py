# ===================================================================================================
# The card lab: one set of facts, five ways to draw it.
#
# The brief was image-first, name over the image, and the platform / language / kind / stars / author /
# install command all legible on the face. Two measurements from `docs/data.json` shape every answer
# below, and both of them are constraints rather than details:
#
#   * `img` is populated on 686 of 1,294 rows -- 53%. Of the top 44 by stars, 30 carry one. So a grid that
#     leads with a screenshot silently demotes 608 projects to a grey rectangle, which is the exact
#     opposite of "help projects get screentime". Every direction here therefore has to answer what the
#     imageless card looks like, and `portrait()` is this file's answer: artwork generated from the
#     project's own facts, no fetch, no file, different for every row.
#   * `first_seen` is empty on all 1,294 rows and `state/first-seen.json` stamps every repo with the
#     `2026-09-03` baseline, so **no project qualifies as new today**. The yellow-glow machinery is built
#     and wired; its qualifying set is empty until an import brings arrivals, which is Phase 0. The states
#     row below labels its NEW card as simulated rather than quietly showing a state that cannot occur.
# ===================================================================================================

# The corpus has no "is it a skill or a harness" column. `cat` *is* that axis -- its fourteen values are
# kinds of thing, not subject areas -- so the chip is the topic, shortened to the one word that fits on a
# card and reads as a noun. Kept as an explicit map rather than a first-word split because four of the
# fourteen would come out wrong ("Context", "Sandbox", "Plugins", "Docs" for a row that is a reading list).
KIND = {
    "Orchestrators & Multi-Agent": "Orchestrator",
    "Coding Agents": "Coding agent",
    "Agent Skills": "Skill",
    "MCP Servers": "MCP server",
    "Frameworks & SDKs": "Framework",
    "Harnesses & Runtime Infra": "Harness",
    "Context, Memory & RAG": "Memory / RAG",
    "Sandbox, Security & Governance": "Sandbox",
    "Observability & Evals": "Evals",
    "Plugins, Themes & Clients": "Plugin",
    "Research & Data Agents": "Research agent",
    "Creative, Voice & Media": "Media",
    "Assistants & Domain Agents": "Assistant",
    "Docs, Learning & Lists": "Reading",
}
# A topic added upstream must not silently render as an empty chip on 1,294 cards.
assert set(KIND) == set(TOPICS), sorted(set(TOPICS) ^ set(KIND))

# Three characters each, so five of them are one uniform row rather than five different widths. The full
# platform name rides along in the `title` and in the container's `aria-label`; see `plat_pills`.
OS_SHORT = ["Win", "WSL", "Mac", "Lnx", "Dkr"]

# Which rows get the gold ring -- and, more importantly, when nothing does.
#
# `first_seen` is a ledger stamp, not a birthday, and the difference decides whether this signal works. On the
# 2026-09-21 corpus every single stamped row shares one date: 7,572 rows, 85% of the atlas, one distinct
# value, because that import was the first to complete after a five-build outage and `state/first-seen.json`
# had nothing for anything it had not already seen. Read naively that is "7,572 new projects", and it put a
# gold ring on 75 of the 125 cards on the browse page -- measured, not estimated. A mark on three cards in
# five is not a mark; the brief asked for "a slight yellow glow if it's new" precisely because new is supposed
# to be rare, and a backfill is the one event that can make every row look new at once while none of them are.
#
# So the cohort has to earn the ring. If the newest stamp covers more than BACKFILL_MAX of the corpus it is a
# backfill rather than a day's arrivals, and it confers nothing. The threshold is a fifth, which is far above
# any real day (a weekly ingest moves tens of rows, not thousands) and far below this event's 85%, so it
# discriminates the two cases without needing to be tuned. The fact itself is not suppressed -- the "First
# indexed" shelf still says 7,572 rows arrived in that import, because that is true and worth showing. What is
# withheld is the *emphasis*, which is the thing a reader reads as "this is unusual".
BACKFILL_MAX = 0.20
_STAMPS = collections.Counter(g(r, "first_seen") for r in ROWS if g(r, "first_seen"))
NEWEST_STAMP = max(_STAMPS) if _STAMPS else ""
STAMPED: set[str] = {g(r, "nwo") for r in ROWS if g(r, "first_seen") == NEWEST_STAMP} if _STAMPS else set()
# A backfill is a fact about the corpus, so it is computed once and reported in main() rather than being
# rediscovered by each renderer -- five callers asking "is this row new" must not be able to disagree.
BACKFILL = bool(STAMPED) and len(STAMPED) > BACKFILL_MAX * len(ROWS)
NEW_SET: set[str] = set() if BACKFILL else STAMPED


def face(row) -> dict:
    """Everything a card face shows, resolved once.

    Five renderers draw the same project below and they must not be able to disagree about what it is --
    which is what happens when each one reaches into the row itself and one of them forgets that `license`
    is empty on 222 rows or that `lists` is `None` rather than 1 when a row was named once."""
    nwo = g(row, "nwo")
    owner, _, _ = nwo.partition("/")
    # 285 of the 1,294 `name` values are already `owner/repo`, because that is how the upstream list wrote
    # them -- so a card that prints the owner above the name renders "mattpocock/" over
    # "mattpocock/skills" on 22% of the corpus. Stripped here rather than in each renderer, and only when
    # the prefix is genuinely this row's owner: 8 more names contain a slash that is part of the name
    # ("DeepSeek V3/R1"), and those must survive untouched.
    name = g(row, "name")
    if name.lower().startswith(owner.lower() + "/"):
        name = name[len(owner) + 1:]
    fresh, age = freshness(row)
    lists = g(row, "lists") or 1
    rank = RANK[nwo]
    states = []
    # Ordered by which one the border gets to show, most newsworthy first, because a card has one border
    # and three of these can be true at once. New beats rare beats hot: arrival is the thing a reader can
    # only learn here, consensus is the thing they would otherwise have to read 39 lists to learn, and
    # "pushed this week" is already carried by the dot next to the age.
    if nwo in NEW_SET:
        states.append("s-new")
    if lists >= 3:
        states.append("s-rare")
    if fresh == "hot":
        states.append("s-hot")
    return {
        "row": row, "nwo": nwo, "owner": owner, "name": name,
        "href": detail_href(row), "url": g(row, "url") or "",
        "topic": TOPICS[g(row, "cat")], "kind": KIND[TOPICS[g(row, "cat")]],
        "fam": family_of(row), "famlab": FAMILIES[family_of(row)][0],
        "lang": g(row, "lang") or "", "lic": g(row, "license") or "",
        "stars": g(row, "stars") or 0, "starsc": compact(g(row, "stars") or 0),
        "rank": rank, "pct": (len(ROWS) - rank) / len(ROWS) * 100,
        "fresh": fresh, "age": age, "lists": lists, "listed_by": g(row, "listed_by") or "",
        "install": g(row, "install") or "", "blurb": blurb(row),
        "img": g(row, "img") or "", "os": g(row, "os") or "NNNNN",
        "ac": accent_for(row), "states": states,
    }


def portrait(f: dict, ratio: str = "16/9") -> str:
    """Card artwork drawn from the project's own facts. The answer for the 608 rows with no screenshot.

    Three properties make this the right kind of fallback rather than a nicer placeholder. It costs nothing
    -- no request, no image file, no build step, just a gradient stack in a style attribute. It is
    *different for every project*, so a grid of imageless rows reads as a grid of distinct things instead
    of 608 copies of one grey box. And it is not decoration: the hue is the topic, the texture is a hash of
    the `nwo`, the arc is where the project sits in the corpus by stars and the watermark is the language.
    Somebody who learns the code can read a portrait from across the room.

    It deliberately does *not* encode the platform verdicts, which an earlier version did as five bars.
    They are already on the card as `plat_pills`, three lines below, and the second encoding bought nothing
    -- it was the same fact in a form that needed the legend the pills exist to avoid. It also could not
    fit: a 16:9 poster tile is 159px tall, the chips take the top 32 and the name stack the bottom 60, so
    two centred marks in the remaining 56px overlapped on 16 of the 24 cards measured. One mark, centred.

    Deterministic on `nwo` via crc32 rather than `hash()`, which is salted per process and would redraw
    every portrait on every build -- turning a page that should be byte-stable into daily churn."""
    h = zlib.crc32(f["nwo"].encode("utf-8"))
    cat = g(f["row"], "cat")
    # Second hue two steps round the five accents, nudged by the hash, so two projects in the same topic
    # are the same family but not the same picture.
    a2 = ACCENTS[(cat + 2 + (h & 3)) % len(ACCENTS)]
    word = (f["lang"] or f["kind"]).upper()
    return (
        f'<span class="pt" aria-hidden="true" style="aspect-ratio:{ratio};'
        f'--p1:{f["ac"]};--p2:var(--accent-{a2});'
        f'--px:{12 + (h >> 4) % 76}%;--py:{8 + (h >> 11) % 64}%;'
        f'--ang:{h % 180}deg;--gap:{7 + (h >> 17) % 10}px;--arc:{f["pct"]:.1f}%">'
        f'<span class="pt-h"></span>'
        f'<span class="pt-w">{esc(word)}</span>'
        f'<span class="pt-r"></span>'
        f'</span>')


def art(f: dict, fallback: str = "portrait", ratio: str = "16/9") -> str:
    """The image slot. A real screenshot when the row has one; otherwise whichever fallback is being shown.

    `social` is `https://opengraph.githubassets.com/1/<nwo>`, GitHub's generated card, which exists for
    every repository -- so 100% of rows can carry *an* image even though only 53% carry a screenshot. It is
    also a third-party request per card and it renders the repo name in Helvetica on a near-white card, so
    a shelf of twelve of them is twelve near-identical white rectangles. The A/B further down shows the
    same imageless project both ways; `portrait` is the default here because it is the one that makes the
    grid legible."""
    if f["img"]:
        return (f'<img src="{esc(f["img"])}" alt="" loading="lazy" decoding="async"'
                f' style="aspect-ratio:{ratio}">')
    if fallback == "social":
        return (f'<img src="https://opengraph.githubassets.com/1/{esc(f["nwo"])}" alt=""'
                f' loading="lazy" decoding="async" style="aspect-ratio:{ratio}">')
    return portrait(f, ratio)


def plat_pills(f: dict, compact_pills: bool = False) -> str:
    """Platform compatibility as five three-letter pills, filled / outlined / dim.

    The five-slot bar meter this file already has (`os_meter`) is smaller and prettier and needs a legend
    to mean anything -- which is fine in a table with a header row and useless on a card that might be the
    only thing a reader ever sees. Three letters need no legend. The three states are the three the ingest
    actually produced, and flattening `Likely` into a yes would be a claim it never made: 577 rows are
    exactly `LLLLN`, so that state is not an edge case, it is nearly half the corpus."""
    names = DATA["os"]
    out, said = [], []
    for i, ch in enumerate(f["os"][:5]):
        label, _, why = VERDICT.get(ch, VERDICT["-"])
        cls = {"Y": "y", "L": "l"}.get(ch, "n")
        out.append(f'<i class="{cls}" title="{esc(names[i])} — {esc(label)}. {esc(why)}">'
                   f'{esc(OS_SHORT[i])}</i>')
        said.append(f"{names[i]} {label.lower()}")
    cls = "plat tight" if compact_pills else "plat"
    return f'<span class="{cls}" aria-label="Platforms: {esc(", ".join(said))}">' + "".join(out) + "</span>"


def title_over(f: dict, where: str = "bl") -> str:
    """The name on the image. `bl` is bottom-left, `tc` is top-centre; the A/B below shows both.

    Bottom-left is the recommendation and there are three reasons. The 608 rows without a screenshot fall
    back to a generated card whose own artwork is centred and top-weighted, and GitHub's social card --
    the other fallback -- puts the repository name in the *upper middle* of the frame, so a top-centre
    overlay lands on top of the one thing already written there. Bottom-left shares a left edge with the
    metadata row underneath it, which makes the card one column of text rather than two alignments. And a
    scrim that darkens upward from the bottom is the one that never covers the subject of a screenshot,
    which is almost always the top two-thirds of a UI."""
    return (f'<span class="ttl {where}">'
            f'<span class="own">{esc(f["owner"])}<span aria-hidden="true">/</span></span>'
            f'<span class="nm">{esc(f["name"])}</span></span>')


def overlay(f: dict, name_at: str = "bl") -> str:
    """The bottom-left stack on the image: platform pills, then the owner, then the name.

    They started side by side -- name bottom-left, pills bottom-right -- and that is measurably wrong at
    the width the poster is designed for. Five pills need about 150px and a 282px card leaves 130 for the
    name, so `everything-claude-code` was drawn straight under the pills with no gap: two separate things
    on one baseline reading as one crowded row. Stacked, they share a left edge with the metadata line
    below the image, the name gets the full card width, and nothing has to be truncated to make room.

    When the name is at the top instead (the A/B's other arm) there is nothing for the pills to collide
    with, so they stay in their own corner."""
    if name_at == "tc":
        return title_over(f, "tc") + plat_pills(f, True)
    return '<span class="ovl">' + plat_pills(f, True) + title_over(f, "bl") + '</span>'


def stars_over(f: dict) -> str:
    return (f'<span class="stz" title="{thousands(f["stars"])} stars — #{f["rank"]} of'
            f' {thousands(len(ROWS))} in the atlas">'
            f'<i aria-hidden="true">&#9733;</i>{esc(f["starsc"])}</span>')


def flags(f: dict) -> str:
    """The word beside the glow.

    A state carried only by a border colour is not carried: it is invisible to anybody who has not been
    told the code, and the gold-vs-violet distinction is one of the two pairs that red-green colour
    blindness flattens. So each state that has a border also has a word, and the border is the thing that
    makes the word findable in a grid of thirty rather than the thing that has to say it alone."""
    out = []
    if "s-new" in f["states"]:
        out.append('<span class="flag new">New</span>')
    if "s-rare" in f["states"]:
        out.append(f'<span class="flag rare" title="{esc(f["listed_by"])}">'
                   f'{f["lists"]} lists</span>')
    return "".join(out)


def lang_chip(f: dict) -> str:
    """The language, with a dot in the topic accent rather than in a per-language colour. A second colour
    axis would fight the first one: this page already spends the five accents on topic, and a card whose
    stripe says one thing and whose dot says another is a card with two legends. 117 rows have no language
    at all, which is why this is a function and not a fragment."""
    if not f["lang"]:
        return ""
    return f'<span class="lang"><i></i>{esc(f["lang"])}</span>'


def sel_attrs(f: dict) -> str:
    """The facts a client-side filter needs, on the card itself.

    Every one of these is already *drawn* on the face -- the family as the seam, the platforms as pills, the
    install command as a box -- so this adds no information to the page, only a machine-readable copy of
    what a reader can already see. That symmetry is the point: a filter that can hide a card for a reason
    the card does not display is a filter nobody can trust.

    On all five renderers rather than only the one surface that filters today, because the alternative is
    discovering in three weeks that the shelf view silently filters on a subset of its cards."""
    return (f' data-fam="{f["fam"]}" data-os="{esc(f["os"])}"'
            f' data-inst="{1 if f["install"] else 0}" data-shot="{1 if f["img"] else 0}"')


def kind_chip(f: dict) -> str:
    """What it is, tinted by its family. One function so the five card renderers cannot drift on the one
    mark that carries the colour code -- and so the tooltip that *teaches* the code is on every card rather
    than on whichever renderer was edited last. The hue is findable, the word is what it means, and the
    title is where a reader who has noticed the colours finds out what they group."""
    return (f'<span class="chip kind" data-fam="{f["fam"]}"'
            f' title="{esc(f["topic"])} — {esc(f["famlab"])}: {esc(FAMILIES[f["fam"]][2])}">'
            f'{esc(f["kind"])}</span>')


def lic_chip(f: dict) -> str:
    return f'<span class="lic">{esc(f["lic"])}</span>' if f["lic"] else ""


def cmdline(f: dict, always: bool = True) -> str:
    """The install command. Absent on 23 rows, and an empty bordered box is worse than nothing."""
    if not f["install"]:
        return ('<div class="cw none"><span>no published install route</span></div>' if always else "")
    return (f'<div class="cw"><code class="cmd">{esc(f["install"])}</code>'
            f'<button class="cp" data-cmd="{esc(f["install"])}" title="Copy">Copy</button></div>')


