# ---------------------------------------------------------------------------------------------------
# Shelves: browsing and discovery, and the arithmetic of screentime
#
# The ranking is the problem. 1,094 of 1,294 projects sit outside the top 200 by stars, and a page whose
# only order is stars shows a reader the same 30 projects every day for ever -- which is a reasonable
# default and a terrible whole design. Every shelf below is a *reason to be shown* that stars cannot buy:
# independent agreement across 39 lists, a push inside the last week, a low star count next to a high
# consensus, a platform, a language, an arrival date. The coverage note at the foot of the page does the
# arithmetic out loud.
# ---------------------------------------------------------------------------------------------------

TOP200 = {g(r, "nwo") for r in RANKED[:200]}


def rotate(pool: list, n: int, salt: str) -> list:
    """Pick `n` of `pool`, stably for one snapshot and differently for the next.

    Sorting by a hash of the snapshot date and the `nwo` gives a shelf that is identical for every reader
    on a given day, changes when the data changes, and does not change when it does not -- which is the
    same churn contract the detail pages keep. crc32 rather than `hash()`, which is salted per process and
    would reshuffle every shelf on every build for no reason.

    The alternative was to sort each pool by stars, and that would quietly undo the whole point: the
    fresh-this-week shelf would be the famous projects that happen to have been pushed this week, which is
    the leaderboard again wearing a different hat."""
    keyed = sorted(pool, key=lambda r: zlib.crc32(f"{salt}|{DATA['snapshot']}|{g(r, 'nwo')}".encode()))
    return keyed[:n]


SHELF_N = 12


def shelf_defs() -> list[dict]:
    """Every shelf, with its pool measured rather than asserted."""
    out = []

    def add(key, title, why, pool, rows=None, href="#"):
        out.append({"key": key, "title": title, "why": why, "pool": pool,
                    "rows": rows if rows is not None else rotate(pool, SHELF_N, key), "href": href})

    consensus = [r for r in ROWS if (g(r, "lists") or 1) >= 3]
    add("consensus", "Named by three or more lists",
        f'{len(consensus)} projects of {thousands(len(ROWS))} were picked independently by three or more of'
        f' the {LISTS} upstream lists this atlas reads. {thousands(LISTS_N[1])} rows were named once, so'
        ' this is the top 1.5% of the corpus by agreement &mdash; and it is a signal a reader cannot get'
        ' from GitHub, because it is not about this repository at all.', consensus)

    week = [r for r in ROWS if (age_days(r) or 999) <= 7]
    add("week", "Shipped in the last seven days",
        f'{len(week)} projects were pushed inside a week of the {DATA["snapshot"]} snapshot.'
        ' Ordered by rotation, not by stars &mdash; sorting this shelf by stars would show the famous'
        ' projects that happen to have shipped this week, which is the leaderboard again.', week)

    gems = [r for r in ROWS if (g(r, "stars") or 0) < 500 and (g(r, "lists") or 1) >= 2]
    ranks = sorted(RANK[g(r, "nwo")] for r in gems)
    med = ranks[len(ranks) // 2] if ranks else 0
    add("gems", "Hidden gems",
        f'{len(gems)} projects under 500 stars that two or more lists named anyway. Their median position'
        f' in the star ranking is <b>#{med}</b> of {thousands(len(ROWS))}, so not one of them will ever'
        ' appear on a first screen ordered by popularity &mdash; and somebody curating a list went out of'
        ' their way twice.', gems, rows=gems[:SHELF_N])

    win = [r for r in ROWS if (g(r, "os") or "N")[0] == "Y"]
    add("win", "Runs natively on Windows",
        f'{len(win)} projects state Windows support in their own README, install route, CI config or'
        ' release assets &mdash; not inferred from the language, stated. This is the shelf that a filter'
        ' can already produce and nobody ever sets, which is the argument for making it a place instead of'
        ' a control.', win)

    for lang, n in [(l, c) for l, c in lang_n.most_common() if l in ("Rust", "Go")]:
        pool = [r for r in ROWS if g(r, "lang") == lang]
        add(f"lang-{lang.lower()}", f"Built in {lang}",
            f'{n} of {thousands(len(ROWS))}. Language is the axis a reader with an existing stack actually'
            ' navigates by, and it is not a proxy for quality, which makes it a fair way to be found.',
            pool)

    tail = [r for r in ROWS if g(r, "nwo") not in TOP200]
    add("deep", "Deep cuts",
        f'{thousands(len(tail))} projects sit outside the top 200 by stars &mdash; {len(tail) * 100 // len(ROWS)}%'
        ' of the atlas, effectively invisible to anybody who scrolls one screen. Twelve of them, rotated by'
        f' the snapshot date: this shelf shows a different twelve on the next build, so over a season the'
        ' whole tail gets a turn.', tail)

    small_topic = min(topic_n.items(), key=lambda kv: kv[1])
    st_rows = [r for r in ROWS if TOPICS[g(r, "cat")] == small_topic[0]]
    add("smallest", f"All of {small_topic[0]}",
        f'The smallest topic in the atlas holds {small_topic[1]} projects against the largest'
        f' {max(topic_n.values())}. At {small_topic[1]} it fits on one shelf entirely, which means this'
        ' category can be read to completion &mdash; something no star ranking will ever offer it.',
        st_rows, rows=st_rows)

    # This shelf was written as the empty state and it is no longer empty, which is the outcome the design
    # was betting on rather than a change of mind. It shipped hardcoded to `[]` against the 2026-09-03
    # snapshot, where `first_seen` was blank on every one of 1,294 rows and there was genuinely nothing to
    # put here; the point of building it anyway was that it would fill itself when the pipeline caught up.
    # The 2026-09-21 ingest stamped 7,572 rows, so it now derives its pool like every other shelf, and the
    # `.empty` branch stays in the stylesheet because a future snapshot with no arrivals is still possible.
    newest = [r for r in ROWS if g(r, "nwo") in STAMPED]
    if BACKFILL:
        why = (f'{thousands(len(newest))} projects carry <code>{NEWEST_STAMP}</code> as the first date the'
               f' atlas recorded them &mdash; {len(newest) * 100 // len(ROWS)}% of everything here, all on one'
               ' day. That is the ledger being filled in after an outage, not a thousand launches, so these'
               ' cards are shown without the gold ring that marks a genuine new arrival. The shelf is the'
               ' fact; the ring is the claim, and only one of them is true today.')
    else:
        why = (f'{thousands(len(newest))} projects were first recorded on <code>{NEWEST_STAMP}</code>,'
               f' {len(newest) * 100 // len(ROWS)}% of the atlas. Every card here carries the gold ring &mdash;'
               ' the only state on the site that spends a hue on the perimeter.')
    add("new", "First indexed " + (NEWEST_STAMP or "&mdash;"), why, newest)
    return out


