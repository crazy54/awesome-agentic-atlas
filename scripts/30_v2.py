def age_days(row) -> int | None:
    p = g(row, "pushed")
    if not p:
        return None
    return (SNAP - datetime.date.fromisoformat(p[:10])).days


def freshness(row) -> tuple[str, str]:
    """(class, label). `hot` is the only one that pulses, and it has to stay scarce to mean anything:
    725 of 1,294 rows are inside thirty days, so thirty days is not news. Seven is."""
    d = age_days(row)
    if d is None:
        return "unk", "unknown"
    if d <= 7:
        return "hot", f"{d}d" if d else "today"
    if d <= 30:
        return "warm", f"{d}d"
    if d <= 180:
        return "ok", f"{d // 30}mo"
    if d <= 365:
        return "cold", f"{d // 30}mo"
    return "stale", f"{d // 365}y"


def os_meter(verdicts: str) -> str:
    """Five slots, one per platform, in `DATA["os"]` order. A half-height slot is a `likely`, which is a
    real third state in this data -- 577 rows are LLLLN -- and flattening it to a yes would be a claim
    the ingest never made."""
    names = DATA["os"]
    out = []
    for i, ch in enumerate((verdicts or "NNNNN")[:5]):
        cls = {"Y": "y", "L": "l"}.get(ch, "n")
        out.append(f'<i class="sl {cls}" title="{esc(names[i])}"></i>')
    return '<span class="meter" aria-hidden="true">' + "".join(out) + "</span>"


