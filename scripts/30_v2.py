def skin_css() -> str:
    """One block per skin, keyed on `data-skin`, plus the default skin's values on bare `:root` so a
    reader with JavaScript off still gets a designed page rather than an unstyled one."""
    out = []
    default = SKINS[DEFAULT_SKIN]["tokens"]
    out.append(":root{\n" + "".join(f"  --{k}:{v};\n" for k, v in default.items()) + "}")
    for sid, skin in SKINS.items():
        body = "".join(f"  --{k}:{v};\n" for k, v in skin["tokens"].items())
        out.append(f"html[data-skin={sid}]{{\n{body}}}")
    return "\n".join(out)


