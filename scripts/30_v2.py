#
# `--lift`, `--lift-hi` and `--scrim` are the three the card work added, and they are deliberately *not*
# `--fx-*` multipliers. Depth is not motion and it is not glow: a drop shadow says "this tile is a thing
# you can pick up", which every skin here wants to say, so all three declare real values and Graphite
# keeps every `--fx-*` at zero while still casting a shadow. What differs is the *character* of the
# depth, which is exactly the kind of thing a skin should own -- Graphite and Glass cast a soft blurred
# shadow and Neon Terminal casts a hard unblurred offset, because a phosphor terminal has no ambient
# light in it to make a penumbra. `--shadow` stays what it was, the panel-and-menu shadow; it is `none`
# in two of the three skins, which is why a card asking for depth had to ask for something else.
# ---------------------------------------------------------------------------------------------------

