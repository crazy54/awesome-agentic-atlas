# Colour that means something: five families over fourteen topics.
#
# The old rule here was `ACCENTS[cat % 5]`, and its own docstring conceded the problem -- it called the
# result "a grouping cue, not a legend", which is a polite way of saying the colour was decorative. Modulo
# fourteen over five pairs topics by their position in an alphabetised list, so Coding Agents and
# Observability & Evals came out the same hue for no reason a reader could ever discover, and two topics
# that obviously belong together came out different. Colour that cannot be learned is noise with a palette.
#
# So the hue is a *family*, and the families are what somebody is actually shopping for. Five hues, not
# fourteen, and five is the ceiling rather than a compromise. Six mutually distinguishable hues do not exist
# in this palette: the sixth would have to sit between gold and coral (orange) or between sky and mint
# (cyan), and either one collapses the distinction it was added to make, worst for the readers who need it
# most. Five families that can each be told apart beats fourteen that cannot.
#
# THE SIXTH FAMILY HAS NO HUE, AND THAT IS THE ANSWER TO A PROBLEM THE FULL CORPUS CREATED.
# This map was written against a 1,294-row snapshot where the five families came out 30/13/37/9/8 per cent --
# balanced enough that any of them could carry a hue. The 2026-09-21 ingest published 8,856 rows, and the
# distribution went to 64/16/10/6/3: `MCP Servers` alone is 4,537 rows, 51% of the atlas, and it was sitting
# inside Build. That breaks the legend in the way a legend actually fails -- not by being hard to read, but by
# being *wrong*. Build meant "things you build on", and four fifths of it was now MCP servers.
#
# Splitting it out is forced. Colouring it is not, and the measurement is what decided that: the largest
# family on the index's first fifty is 34%, and on the first two hundred it is 35%, so what a reader sees on
