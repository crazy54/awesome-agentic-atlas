def heat(n: int) -> float:
    """Cell count -> 0..1 tint strength, on a square root.

    Linear is wrong here and the distribution says why: the largest crossing holds 275 projects and the
    median non-empty one holds 6.5. On a linear ramp that median cell tints at 2%, which is
    indistinguishable from the 130 empty ones, and the matrix collapses into one bright corner surrounded
    by grey -- a picture of its own maximum rather than of the corpus. The square root lifts that median
    to 15% while still leaving the top cell clearly the top cell, which is what a heat map is for."""
    return (n / CELL_MAX) ** 0.5 if n else 0.0


