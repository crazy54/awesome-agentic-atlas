def slug(nwo: str) -> tuple[str, str]:
    """`owner/Name` -> ("owner", "name"). Lowercased, which `22_detail.py` asserts is lossless here: 442 of
    the 1,294 `nwo` values carry capitals and no two collide once folded."""
    owner, _, name = nwo.partition("/")
    return owner.lower(), name.lower()


def blurb(row) -> str:
    """The description, with an ellipsis added when the upstream 400-character cap cut it mid-clause.

    Whatever writes `blurb` truncates hard at 400 and adds no mark, so 97 of the 1,288 descriptions end on a
    dangling word -- "Works across Claude Code, Codex, Cursor, OpenCode, and" -- which reads as a rendering
    bug in the page rather than as a description that continues elsewhere.

    The test is length *and* punctuation, not punctuation alone: 915 of the 1,288 have no full stop because
    they were written without one, and marking those would be inventing truncation on 832 complete
    sentences. 396 rather than 400 because the cap is applied after a strip, so the last few characters are
    not a reliable count. Fixing the cap belongs upstream; this only stops the page misreporting it."""
    b = (g(row, "blurb") or "").rstrip()
    if len(b) >= 396 and b[-1:] not in (".", "!", "?", ")", '"', ""):
        return b + "…"
    return b


def related(row, k: int = 6) -> list:
    """Same topic, closest first -- and ordered the way the shipped page orders it, by shared harnesses,
    then list count, then name. Deliberately *not* by stars, for the same reason nothing else on this page
    is: a star-ranked list of six would reshuffle on 1,294 pages most days and put the stage back to
    rewriting the whole tree on every run."""
    mine = set(g(row, "targets"))
    peers = [p for p in BY_CAT[g(row, "cat")] if g(p, "nwo") != g(row, "nwo")]
    peers.sort(key=lambda p: (-len(mine & set(g(p, "targets"))),
                              -(g(p, "lists") or 1),
                              g(p, "name").lower()))
    return peers[:k]


