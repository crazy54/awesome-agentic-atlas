def showcase() -> list:
    """The project the switcher opens on.

    Picked for coverage rather than for rank: the row in the built set with the most of its optional fields
    populated -- own screenshot, declared licence, install route, named by more than one list, at least one
    harness -- and the best-ranked among ties. A demo tab that lands on a page with three empty sections is
    judging the data, not the design. The sparse states are still one click away through the cards, which is
    the honest way round."""
    pool = RANKED[:max(CARDS, LIST_ROWS)]

    def filled(r) -> int:
        return sum((bool(g(r, "img")), bool(g(r, "license")), bool(g(r, "install")),
                    (g(r, "lists") or 1) > 1, bool(g(r, "targets"))))

    return max(pool, key=lambda r: (filled(r), -RANK[g(r, "nwo")]))


