def facet_group(kick: str, counts: list[tuple[str, int]], total: int, hue: str,
                cut: int = 8, hue_of=None) -> str:
    """One facet group. `hue` colours the whole group's count bars; `hue_of` overrides it per row, which is
    what the Topic group uses so a facet's bar is the same colour as the cards it filters to. Every other
    group keeps a single hue, because a language or a licence has no family to belong to and inventing one
    would put five meaningless colours next to five meaningful ones."""
    head = (f'<div class="fg"><div class="fh"><span>{esc(kick)}</span>'
            f'<em>{len(counts)}</em></div>')
    rows = []
    top = max((n for _, n in counts), default=1)
    for i, (label, n) in enumerate(counts):
        pct = round(n / top * 100, 1)
        hidden = ' hidden' if i >= cut else ''
        rows.append(
            f'<button class="frow" aria-pressed="false" data-w="{pct}%"'
            f' style="--fc:var(--accent-{hue_of(label) if hue_of else hue})"{hidden}>'
            f'<span class="lb">{esc(label)}</span>'
            f'<span class="ct">{thousands(n)}</span></button>')
    tail = ''
    if len(counts) > cut:
        tail = (f'<button class="more" data-more>{len(counts) - cut} more'
                f' <span aria-hidden="true">+</span></button>')
    return head + "".join(rows) + tail + "</div>"


