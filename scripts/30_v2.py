def plane_map() -> dict[str, str]:
    """Skin id -> the colour the browser chrome should take, for the pre-paint `theme-color` literal.
    `--plane` is the wrong token for it under glass, where that value is a translucent white that means
    nothing on its own; `--rail-bg` is what actually sits at the top of the viewport, and `--surface` is
    the fallback for a skin whose rail is a plain `var(--plane)`."""
    out = {}
    for sid, skin in SKINS.items():
        tok = skin["tokens"]
        v = tok.get("rail-bg") or tok["plane"]
        out[sid] = tok["surface"] if v.startswith("var(") else v
    return out


